/// Texte de `key` dans la langue choisie d'après `languages` (langues préférées, la première d'abord).
/// Seule la première langue compte : ["fr-CA", "en"] → français ; ["en", "fr"] → anglais ; [] → anglais.
/// Clé inconnue → la clé elle-même (« menu.qiut » s'affiche tel quel : la faute se voit dans le menu).
func localized(_ key: String, languages: [String]) -> String {
    guard let entry = strings[key] else { return key }
    let firstLanguage = languages.first ?? ""
    let isFrench = firstLanguage.hasPrefix("fr")
    return isFrench ? entry.fr : entry.en
}

/// Texte de `key` dans la langue de macOS (Réglages Système > Général > Langue et région).
func L(_ key: String) -> String {
    return localized(key, languages: Locale.preferredLanguages)
}

// MARK: - Historique en mémoire

struct Flavor {
    let type: String
    let data: Data
}

struct Entry {
    let id: Int
    let label: String
    let search: String
    let key: String
    let items: [[Flavor]]
    let size: Int

    init(id: Int, label: String, search: String, key: String, items: [[Flavor]]) {
        self.id = id
        self.label = label
        self.search = search
        self.key = key
        self.items = items
        var total = 0
        for row in items { for f in row { total += f.data.count } }
        self.size = total
    }
}

func sha256Hex(_ data: Data) -> String {
    SHA256.hash(data: data).map { String(format: "%02x", $0) }.joined()
}

final class History {
    private(set) var entries: [Entry] = []   // du plus récent au plus ancien
    private var nextID = 0

    /// Garde tout ce qui est sur le presse-papiers, tous formats confondus.
    /// Renvoie true si l'historique a changé.
    func capture(_ pb: NSPasteboard) -> Bool {
        guard let pbItems = pb.pasteboardItems, !pbItems.isEmpty else { return false }
        let allTypes = Set(pbItems.flatMap { $0.types.map { $0.rawValue } })
        // Les anciens noms (ex. "Pasteboard generator type") n'apparaissent que dans pb.types,
        // pas dans les types des éléments (qui exposent un "dyn.…" généré) : on vérifie les deux listes.
        let declaredTypes = Set((pb.types ?? []).map { $0.rawValue })
        guard allTypes.isDisjoint(with: ignoredTypes),
              declaredTypes.isDisjoint(with: ignoredTypes) else { return false }

        // Lecture format par format : on abandonne dès que le budget est dépassé,
        // sans lire les formats suivants.
        var items: [[Flavor]] = []
        var hasher = SHA256()
        var read = 0
        for item in pbItems {
            var flavors: [Flavor] = []
            for t in item.types where !t.rawValue.lowercased().contains("promise") {
                guard let d = item.data(forType: t) else { continue }
                read += d.count
                guard read <= maxMemoryBytes else { return false }   // copie trop grosse : non conservée
                flavors.append(Flavor(type: t.rawValue, data: d))
                hasher.update(data: Data(t.rawValue.utf8))
                hasher.update(data: d)
            }
            if !flavors.isEmpty { items.append(flavors) }
        }
        guard !items.isEmpty else { return false }

        let text = pb.string(forType: .string)
        let key: String
        if let text = text, !text.isEmpty {
            key = "t:" + sha256Hex(Data(text.utf8))
        } else {
            key = "d:" + hasher.finalize().map { String(format: "%02x", $0) }.joined()
        }

        let label = History.label(for: pb, text: text, types: allTypes)
        let search = String((text ?? label).prefix(searchableLength))
        nextID += 1
        let entry = Entry(id: nextID, label: label, search: search, key: key, items: items)

        // Même contenu déjà présent : on le remonte en tête au lieu de le dupliquer.
        entries.removeAll { $0.key == key }
        entries.insert(entry, at: 0)

        var total = 0
        for e in entries { total += e.size }
        while total > maxMemoryBytes, let last = entries.last {
            total -= last.size
            entries.removeLast()
        }
        return true
    }

    static func label(for pb: NSPasteboard, text: String?, types: Set<String>) -> String {
        if let urls = pb.readObjects(forClasses: [NSURL.self],
                                     options: [.urlReadingFileURLsOnly: true]) as? [URL],
           !urls.isEmpty {
            let names = urls.map { $0.lastPathComponent }
            let extra = names.count > 3 ? " +\(names.count - 3)" : ""
            return "📄 " + names.prefix(3).joined(separator: ", ") + extra
        }
        if let text = text {
            let flat = text.split(whereSeparator: { $0.isWhitespace }).joined(separator: " ")
            if !flat.isEmpty { return String(flat.prefix(300)) }
        }
        if let image = NSImage(pasteboard: pb) {
            return "🖼 Image \(Int(image.size.width))×\(Int(image.size.height))"
        }
        return "[\(types.sorted().first ?? "?")]"
    }

    /// Remet un élément sur le presse-papiers, avec tous ses formats (ou en texte brut).
    func write(_ e: Entry, plain: Bool, to pb: NSPasteboard) {
        if plain, let s = fullText(e) {
            pb.clearContents()
            pb.setString(s, forType: .string)
            return
        }
        var objects: [NSPasteboardItem] = []
        for row in e.items {
            let item = NSPasteboardItem()
            for f in row { item.setData(f.data, forType: NSPasteboard.PasteboardType(f.type)) }
            objects.append(item)
        }
        pb.clearContents()
        pb.writeObjects(objects)
    }

    private func fullText(_ e: Entry) -> String? {
        let stringType = NSPasteboard.PasteboardType.string.rawValue
        for row in e.items {
            for f in row where f.type == stringType {
                if let s = String(data: f.data, encoding: .utf8) { return s }
            }
        }
        return nil
    }

    func filtered(_ query: String) -> [Entry] {
        let q = query.trimmingCharacters(in: .whitespaces)
        guard !q.isEmpty else { return entries }
        let opts: String.CompareOptions = [.caseInsensitive, .diacriticInsensitive]
        return entries.filter {
            $0.search.range(of: q, options: opts) != nil || $0.label.range(of: q, options: opts) != nil
        }
    }

    func touch(_ id: Int) {
        guard let i = entries.firstIndex(where: { $0.id == id }) else { return }
        let e = entries.remove(at: i)
        entries.insert(e, at: 0)
    }

    func delete(_ id: Int) {
        entries.removeAll { $0.id == id }
    }

    func clear() {
        entries.removeAll()
    }
}

/// Les versions précédentes écrivaient sur le disque : on efface ce dossier.
/// Renvoie un message si l'effacement échoue.
func removeOldStorage() -> String? {
    let fm = FileManager.default
    let old = fm.urls(for: .applicationSupportDirectory, in: .userDomainMask)[0]
        .appendingPathComponent("ClipHistoryApp", isDirectory: true)
    guard fm.fileExists(atPath: old.path) else { return nil }
    do {
        try fm.removeItem(at: old)
        return nil
    } catch {
        // Notre phrase suit la langue de l'app (L), la cause vient de macOS, déjà traduite.
        // Ex. (Mac en anglais) : "Couldn't delete the folder /Users/moi/Library/Application Support/ClipHistoryApp.\n
        //   You don't have permission to access “ClipHistoryApp”."
        let sentence = String(format: L("alert.oldStorage.info"), old.path)
        let systemReason = error.localizedDescription
        return sentence + "\n" + systemReason
    }
}

// MARK: - Raccourci global (Carbon, sans autorisation spéciale)

var hotKeyAction: (() -> Void)?

func registerHotKey() -> Bool {
    var spec = EventTypeSpec(eventClass: OSType(kEventClassKeyboard),
                             eventKind: UInt32(kEventHotKeyPressed))
    _ = InstallEventHandler(GetApplicationEventTarget(), { _, _, _ in
        hotKeyAction?()
        return 0
    }, 1, &spec, nil, nil)

    var ref: EventHotKeyRef?
    let hotKeyID = EventHotKeyID(signature: OSType(0x434C_4950), id: 1) // 'CLIP'
    let status = RegisterEventHotKey(hotKeyCode, hotKeyModifiers, hotKeyID,
                                     GetApplicationEventTarget(), 0, &ref)
    return status == 0
}

