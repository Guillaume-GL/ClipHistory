final class RowView: NSTableCellView {
    let title = NSTextField(labelWithString: "")
    let hint = NSTextField(labelWithString: "")

    override init(frame: NSRect) {
        super.init(frame: frame)
        title.lineBreakMode = .byTruncatingTail
        title.maximumNumberOfLines = 1
        title.setContentCompressionResistancePriority(.defaultLow, for: .horizontal)
        hint.font = .systemFont(ofSize: 11)
        hint.textColor = .secondaryLabelColor
        hint.setContentHuggingPriority(.required, for: .horizontal)
        hint.setContentCompressionResistancePriority(.required, for: .horizontal)
        for v in [title, hint] {
            v.translatesAutoresizingMaskIntoConstraints = false
            addSubview(v)
        }
        NSLayoutConstraint.activate([
            title.leadingAnchor.constraint(equalTo: leadingAnchor, constant: 8),
            title.centerYAnchor.constraint(equalTo: centerYAnchor),
            hint.leadingAnchor.constraint(greaterThanOrEqualTo: title.trailingAnchor, constant: 8),
            hint.trailingAnchor.constraint(equalTo: trailingAnchor, constant: -8),
            hint.centerYAnchor.constraint(equalTo: centerYAnchor),
        ])
        textField = title
    }

    required init?(coder: NSCoder) { fatalError("init(coder:) non utilisé") }
}

final class AppDelegate: NSObject, NSApplicationDelegate, NSWindowDelegate, NSMenuDelegate,
                         NSTableViewDataSource, NSTableViewDelegate, NSSearchFieldDelegate {
    let history = History()
    let defaults = UserDefaults.standard
    var shown: [Entry] = []
    var lastChange = 0
    var targetPID: pid_t?              // app au premier plan à l'ouverture de la fenêtre
    var recentApps: Set<String> = []   // apps passées au premier plan depuis le dernier sondage

    var statusItem: NSStatusItem!
    var panel: Panel!
    var search: NSSearchField!
    var table: NSTableView!
    var keyMonitor: Any?

    var paused: Bool {
        get { defaults.bool(forKey: "paused") }
        set { defaults.set(newValue, forKey: "paused") }
    }
    var autoPaste: Bool {
        get { defaults.bool(forKey: "autoPaste") }
        set { defaults.set(newValue, forKey: "autoPaste") }
    }
    var excludedApps: [String] {
        get { defaults.stringArray(forKey: "excludedApps") ?? [] }
        set { defaults.set(newValue, forKey: "excludedApps") }
    }

    func applicationDidFinishLaunching(_ notification: Notification) {
        defaults.register(defaults: [
            "paused": false,
            "autoPaste": true,
            "excludedApps": defaultExcludedApps,
        ])

        installEditMenu()
        buildStatusItem()
        buildPanel()

        // Ce qui est déjà copié avant le lancement n'est pas importé.
        lastChange = NSPasteboard.general.changeCount
        NSWorkspace.shared.notificationCenter.addObserver(
            self, selector: #selector(appActivated(_:)),
            name: NSWorkspace.didActivateApplicationNotification, object: nil)
        let timer = Timer(timeInterval: pollInterval, target: self,
                          selector: #selector(poll), userInfo: nil, repeats: true)
        RunLoop.main.add(timer, forMode: .common)

        keyMonitor = NSEvent.addLocalMonitorForEvents(matching: .keyDown) { [weak self] ev in
            guard let self = self, self.panel.isVisible, ev.window === self.panel else { return ev }
            return self.handleKey(ev) ? nil : ev
        }

        hotKeyAction = { [weak self] in self?.togglePanel() }
        if !registerHotKey() {
            alert("Le raccourci \(hotKeyLabel) est déjà utilisé par une autre app.",
                  info: "Change hotKeyCode / hotKeyModifiers en haut de main.swift puis relance build.sh.")
        }
        if let problem = removeOldStorage() {
            alert("Ancien historique encore présent sur le disque.", info: problem)
        }
    }

    // MARK: Surveillance du presse-papiers

    @objc func appActivated(_ notification: Notification) {
        if let app = notification.userInfo?[NSWorkspace.applicationUserInfoKey] as? NSRunningApplication,
           let bundleID = app.bundleIdentifier {
            recentApps.insert(bundleID)
        }
    }

    /// Prudent : si une app exclue a été au premier plan à un moment depuis le dernier sondage,
    /// la copie n'est pas enregistrée (évite le contournement par changement rapide d'app).
    @objc func poll() {
        let current = NSWorkspace.shared.frontmostApplication?.bundleIdentifier
        if let current = current { recentApps.insert(current) }
        defer { recentApps = current.map { [$0] } ?? [] }

        let pb = NSPasteboard.general
        guard pb.changeCount != lastChange else { return }
        lastChange = pb.changeCount
        if paused { return }
        if !recentApps.isDisjoint(with: excludedApps) { return }
        if history.capture(pb), panel.isVisible { reload(selecting: 0) }
    }

    // MARK: Menus

    func installEditMenu() {
        // Sans menu Édition, ⌘C / ⌘V / ⌘A ne marchent pas dans le champ de recherche.
        let main = NSMenu()
        let editItem = NSMenuItem()
        main.addItem(editItem)
        let edit = NSMenu(title: "Édition")
        edit.addItem(withTitle: "Couper", action: #selector(NSText.cut(_:)), keyEquivalent: "x")
        edit.addItem(withTitle: "Copier", action: #selector(NSText.copy(_:)), keyEquivalent: "c")
        edit.addItem(withTitle: "Coller", action: #selector(NSText.paste(_:)), keyEquivalent: "v")
        edit.addItem(withTitle: "Tout sélectionner", action: #selector(NSText.selectAll(_:)), keyEquivalent: "a")
        editItem.submenu = edit
        NSApp.mainMenu = main
    }

    func buildStatusItem() {
        statusItem = NSStatusBar.system.statusItem(withLength: NSStatusItem.squareLength)
        statusItem.button?.image =
            NSImage(systemSymbolName: "list.clipboard", accessibilityDescription: "Historique du presse-papiers")
            ?? NSImage(systemSymbolName: "doc.on.clipboard", accessibilityDescription: "Historique du presse-papiers")
        let menu = NSMenu()
        menu.delegate = self
        menuNeedsUpdate(menu)
        statusItem.menu = menu
    }

    /// Menu reconstruit à chaque ouverture, pour proposer d'exclure l'app au premier plan.
    func menuNeedsUpdate(_ menu: NSMenu) {
        menu.removeAllItems()
        menu.addItem(item("Afficher l'historique (\(hotKeyLabel))", #selector(togglePanel)))
        menu.addItem(.separator())

        let pause = item("Mettre la capture en pause", #selector(togglePause))
        pause.state = paused ? .on : .off
        menu.addItem(pause)
        let auto = item("Coller automatiquement", #selector(toggleAutoPaste))
        auto.state = autoPaste ? .on : .off
        menu.addItem(auto)
        let login = item("Ouvrir à la connexion", #selector(toggleLogin))
        login.state = SMAppService.mainApp.status == .enabled ? .on : .off
        menu.addItem(login)
        menu.addItem(.separator())

        if let front = NSWorkspace.shared.frontmostApplication,
           let bundleID = front.bundleIdentifier,
           bundleID != Bundle.main.bundleIdentifier,
           !excludedApps.contains(bundleID) {
            let exclude = item("Ne plus capturer depuis « \(front.localizedName ?? bundleID) »",
                               #selector(excludeApp(_:)))
            exclude.representedObject = bundleID
            menu.addItem(exclude)
        }
        let excludedMenu = NSMenu()
        for bundleID in excludedApps {
            let i = item(appName(bundleID), #selector(includeApp(_:)))
            i.representedObject = bundleID
            i.state = .on
            i.toolTip = "Cliquer pour capturer à nouveau depuis cette app"
            excludedMenu.addItem(i)
        }
        if excludedApps.isEmpty { excludedMenu.addItem(withTitle: "Aucune", action: nil, keyEquivalent: "") }
        let excludedItem = NSMenuItem(title: "Apps exclues", action: nil, keyEquivalent: "")
        excludedItem.submenu = excludedMenu
        menu.addItem(excludedItem)
        menu.addItem(.separator())

        menu.addItem(item("Vider l'historique et le presse-papiers", #selector(clearHistory)))
        menu.addItem(item("Quitter ClipHistory", #selector(quit)))
    }

    func item(_ title: String, _ action: Selector) -> NSMenuItem {
        let i = NSMenuItem(title: title, action: action, keyEquivalent: "")
        i.target = self
        return i
    }

    func appName(_ bundleID: String) -> String {
        if let url = NSWorkspace.shared.urlForApplication(withBundleIdentifier: bundleID) {
            return FileManager.default.displayName(atPath: url.path)
        }
        return bundleID
    }

    @objc func togglePause() { paused.toggle() }

    @objc func toggleAutoPaste() {
        autoPaste.toggle()
        if autoPaste { requestAccessibility() }
    }

    @objc func excludeApp(_ sender: NSMenuItem) {
        guard let bundleID = sender.representedObject as? String else { return }
        excludedApps = excludedApps + [bundleID]
    }

    @objc func includeApp(_ sender: NSMenuItem) {
        guard let bundleID = sender.representedObject as? String else { return }
        excludedApps = excludedApps.filter { $0 != bundleID }
    }

    @objc func toggleLogin() {
        do {
            if SMAppService.mainApp.status == .enabled {
                try SMAppService.mainApp.unregister()
            } else {
                try SMAppService.mainApp.register()
            }
        } catch {
            alert("Impossible de modifier l'ouverture à la connexion.", info: error.localizedDescription)
        }
    }

    @objc func clearHistory() {
        history.clear()
        shown = []
        let pb = NSPasteboard.general
        pb.clearContents()
        lastChange = pb.changeCount
        if panel.isVisible { reload(selecting: 0) }
    }

    @objc func quit() {
        NSApp.terminate(nil)
    }

    func alert(_ message: String, info: String = "") {
        NSApp.activate(ignoringOtherApps: true)
        let a = NSAlert()
        a.messageText = message
        a.informativeText = info
        a.runModal()
    }

    func requestAccessibility() {
        let opts = [kAXTrustedCheckOptionPrompt.takeUnretainedValue() as String: true] as CFDictionary
        _ = AXIsProcessTrustedWithOptions(opts)
    }

    // MARK: Fenêtre

    func buildPanel() {
        panel = Panel(contentRect: NSRect(x: 0, y: 0, width: 460, height: 420),
                      styleMask: [.borderless, .nonactivatingPanel],
                      backing: .buffered, defer: false)
        panel.isFloatingPanel = true
        panel.level = .statusBar
        panel.collectionBehavior = [.auxiliary, .moveToActiveSpace, .fullScreenAuxiliary]
        panel.hidesOnDeactivate = false
        panel.isMovableByWindowBackground = true
        panel.isOpaque = false
        panel.backgroundColor = .clear
        panel.hasShadow = true
        panel.delegate = self

        let bg = NSVisualEffectView()
        bg.material = .popover
        bg.blendingMode = .behindWindow
        bg.state = .active
        bg.wantsLayer = true
        bg.layer?.cornerRadius = 12
        bg.layer?.masksToBounds = true
        panel.contentView = bg

        search = NSSearchField()
        search.placeholderString = "Rechercher dans l'historique"
        search.delegate = self
        search.focusRingType = .none

        table = NSTableView()
        let column = NSTableColumn(identifier: NSUserInterfaceItemIdentifier("c"))
        column.width = 440
        table.addTableColumn(column)
        table.headerView = nil
        table.style = .plain
        table.rowHeight = 26
        table.intercellSpacing = NSSize(width: 0, height: 2)
        table.backgroundColor = .clear
        table.columnAutoresizingStyle = .lastColumnOnlyAutoresizingStyle
        table.refusesFirstResponder = true
        table.dataSource = self
        table.delegate = self
        table.target = self
        table.action = #selector(rowClicked)

        let scroll = NSScrollView()
        scroll.documentView = table
        scroll.hasVerticalScroller = true
        scroll.autohidesScrollers = true
        scroll.drawsBackground = false

        let footer = NSTextField(labelWithString: "↩ Coller   ⌥↩ Texte brut   ⌘1–9 Accès direct   ⌘⌫ Supprimer   Échap Fermer")
        footer.font = .systemFont(ofSize: 10)
        footer.textColor = .secondaryLabelColor
        footer.alignment = .center
        footer.lineBreakMode = .byTruncatingTail

        for v in [search!, scroll, footer] as [NSView] {
            v.translatesAutoresizingMaskIntoConstraints = false
            bg.addSubview(v)
        }
        NSLayoutConstraint.activate([
            search.topAnchor.constraint(equalTo: bg.topAnchor, constant: 10),
            search.leadingAnchor.constraint(equalTo: bg.leadingAnchor, constant: 10),
            search.trailingAnchor.constraint(equalTo: bg.trailingAnchor, constant: -10),
            scroll.topAnchor.constraint(equalTo: search.bottomAnchor, constant: 8),
            scroll.leadingAnchor.constraint(equalTo: bg.leadingAnchor, constant: 6),
            scroll.trailingAnchor.constraint(equalTo: bg.trailingAnchor, constant: -6),
            scroll.bottomAnchor.constraint(equalTo: footer.topAnchor, constant: -6),
            footer.leadingAnchor.constraint(equalTo: bg.leadingAnchor, constant: 10),
            footer.trailingAnchor.constraint(equalTo: bg.trailingAnchor, constant: -10),
            footer.bottomAnchor.constraint(equalTo: bg.bottomAnchor, constant: -8),
        ])
    }

    @objc func togglePanel() {
        if panel.isVisible { hidePanel() } else { showPanel() }
    }

    func showPanel() {
        targetPID = NSWorkspace.shared.frontmostApplication?.processIdentifier
        search.stringValue = ""
        reload(selecting: 0)

        // Ouvre la fenêtre au niveau du pointeur, sans sortir de l'écran.
        let mouse = NSEvent.mouseLocation
        let screen = NSScreen.screens.first(where: { NSMouseInRect(mouse, $0.frame, false) }) ?? NSScreen.main
        var origin = NSPoint(x: mouse.x, y: mouse.y - panel.frame.height)
        if let vf = screen?.visibleFrame {
            origin.x = min(max(origin.x, vf.minX), vf.maxX - panel.frame.width)
            origin.y = min(max(origin.y, vf.minY), vf.maxY - panel.frame.height)
        }
        panel.setFrameOrigin(origin)
        panel.orderFrontRegardless()
        panel.makeKey()
        panel.makeFirstResponder(search)
        table.sizeLastColumnToFit()
        panel.invalidateShadow()
    }

    func hidePanel() {
        panel.orderOut(nil)
        shown = []              // ne garde pas de références après fermeture
        table.reloadData()
    }

    func windowDidResignKey(_ notification: Notification) {
        hidePanel()
    }

    func reload(selecting row: Int) {
        shown = history.filtered(search.stringValue)
        table.reloadData()
        select(row)
    }

    func select(_ row: Int) {
        guard !shown.isEmpty else { return }
        let r = max(0, min(shown.count - 1, row))
        table.selectRowIndexes(IndexSet(integer: r), byExtendingSelection: false)
        table.scrollRowToVisible(r)
    }

    func controlTextDidChange(_ obj: Notification) {
        reload(selecting: 0)
    }

    // MARK: Clavier

    func handleKey(_ ev: NSEvent) -> Bool {
        let flags = ev.modifierFlags.intersection(.deviceIndependentFlagsMask)
        switch ev.keyCode {
        case 53:                                   // Échap
            hidePanel(); return true
        case 125:                                  // ↓
            select(table.selectedRow + 1); return true
        case 126:                                  // ↑
            select(table.selectedRow - 1); return true
        case 36, 76:                               // Entrée
            paste(row: table.selectedRow, plain: flags.contains(.option)); return true
        case 51 where flags.contains(.command):    // ⌘⌫
            deleteSelected(); return true
        default:
            break
        }
        if flags.contains(.command), let n = digitKeyCodes.firstIndex(of: ev.keyCode) {
            paste(row: n, plain: flags.contains(.option)); return true
        }
        return false
    }

    @objc func rowClicked() {
        let r = table.clickedRow
        if r >= 0 { paste(row: r, plain: NSEvent.modifierFlags.contains(.option)) }
    }

    func deleteSelected() {
        let r = table.selectedRow
        guard r >= 0, r < shown.count else { return }
        history.delete(shown[r].id)
        reload(selecting: r)
    }

    // MARK: Collage

    func paste(row: Int, plain: Bool) {
        guard row >= 0, row < shown.count else { return }
        let e = shown[row]
        let pb = NSPasteboard.general
        history.write(e, plain: plain, to: pb)
        lastChange = pb.changeCount            // ne pas ré-enregistrer notre propre écriture
        history.touch(e.id)
        hidePanel()
        if autoPaste { perform(#selector(sendCmdV), with: nil, afterDelay: 0.08) }
    }

    /// N'envoie ⌘V que si l'app au premier plan est toujours celle d'où la fenêtre a été ouverte.
    /// Sinon l'élément reste simplement sur le presse-papiers.
    @objc func sendCmdV() {
        guard AXIsProcessTrusted() else { requestAccessibility(); return }
        guard let pid = targetPID,
              NSWorkspace.shared.frontmostApplication?.processIdentifier == pid else { return }
        let source = CGEventSource(stateID: .combinedSessionState)
        let v = CGKeyCode(kVK_ANSI_V)
        let down = CGEvent(keyboardEventSource: source, virtualKey: v, keyDown: true)
        let up = CGEvent(keyboardEventSource: source, virtualKey: v, keyDown: false)
        down?.flags = .maskCommand
        up?.flags = .maskCommand
        down?.post(tap: .cgSessionEventTap)
        up?.post(tap: .cgSessionEventTap)
    }

    // MARK: Tableau

    func numberOfRows(in tableView: NSTableView) -> Int {
        shown.count
    }

    func tableView(_ tableView: NSTableView, viewFor tableColumn: NSTableColumn?, row: Int) -> NSView? {
        let id = NSUserInterfaceItemIdentifier("row")
        let cell: RowView
        if let reused = tableView.makeView(withIdentifier: id, owner: self) as? RowView {
            cell = reused
        } else {
            cell = RowView(frame: .zero)
            cell.identifier = id
        }
        let e = shown[row]
        cell.title.stringValue = e.label
        cell.hint.stringValue = row < 9 ? "⌘\(row + 1)" : ""
        cell.toolTip = String(e.search.prefix(500))
        return cell
    }
